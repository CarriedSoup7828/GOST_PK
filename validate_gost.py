# 6. Рисунки Е.11 / Е.12 / Е.13
# =========================================================================
def validate_fig_E11_E13():
    head('6. РИСУНКИ Е.11 / Е.12 / Е.13 — свойства воды и пара на линии насыщения')
    water = th.Fluid('Water')
    R_ud = 461.526                      # п. Е.4.2

    print(f'  {"Р1, МПа":>8} {"Z (Е.11)":>10} {"Tr (Е.12)":>11} {"rho_l (Е.13)":>13}')
    print(' ' + THIN)
    for P1 in (0.1e6, 0.5e6, 1.0e6, 5.0e6, 10.0e6, 20.0e6, 22.0e6):
        Ts = water.T_sat(P1)
        Z = P1 / (water.rho_gas_sat(P1) * R_ud * Ts)         # (Е.3.13)
        print(f'  {P1/1e6:8.2f} {Z:10.4f} {Ts/water.T_crit:11.4f} '
              f'{water.rho_liq_sat(P1):13.1f}')
    print(' ' + THIN)

    Ts01, Ts22 = water.T_sat(0.1e6), water.T_sat(22.0e6)
    check('Е.11: Z при 0,1 МПа (график ~0,98)',
          0.1e6 / (water.rho_gas_sat(0.1e6) * R_ud * Ts01), 0.96, 1.00)
    check('Е.11: Z при 22 МПа (график ~0,25...0,27)',
          22e6 / (water.rho_gas_sat(22e6) * R_ud * Ts22), 0.22, 0.30)
    check('Е.12: Tr при 0,1 МПа (график ~0,57)', Ts01 / water.T_crit, 0.56, 0.59)
    check('Е.12: Tr при 22 МПа (график ~1,0)', Ts22 / water.T_crit, 0.99, 1.001)
    check('Е.13: rho_l при 0,1 МПа (график ~960)',
          water.rho_liq_sat(0.1e6), 940.0, 975.0, ' кг/м3')
    check('Е.13: rho_l при 22 МПа (график ~320...380)',
          water.rho_liq_sat(22e6), 300.0, 400.0, ' кг/м3')


