"""
ВАЛИДАЦИЯ расчёта против независимых эталонов.

В отличие от tests/test_gost.py (который проверяет формулы «сами на себя»),
здесь код сверяется с ДАННЫМИ, посчитанными не нами:

  1. Таблица И.1        — критические отношения давлений для 20 реальных сред
  2. Рисунок Е.2        — beta_кр и Кп кр для постоянного показателя изоэнтропы
  3. Рисунки Е.3, Е.4   — то же для омега-метода
  4. Рисунки Е.5, Е.6   — коэффициент Кb
  5. Рисунки Е.9, Е.10  — Кп кр для ВЛАЖНОГО ВОДЯНОГО ПАРА  <<< главный эталон
  6. Рисунки Е.11-Е.13  — Z, Tr, rho_l на линии насыщения воды
  7. Рисунок И.1        — коэффициент Kw
  8. Рисунок И.3        — коэффициент Kv
  9. API 520 / ISO 4126 — промышленная формула расчёта площади сброса

Почему п. 5 — главный эталон
----------------------------
П. Е.4.1: «в данном разделе приведены готовые к использованию графики,
рассчитанные МЕТОДОМ ПРЯМОГО ИНТЕГРИРОВАНИЯ по наиболее точным на сегодня
уравнениям расчёта теплофизических свойств и фазового равновесия воды и
пара, предложенным Международной Ассоциацией по Свойствам Воды и Водяного
Пара (IAPWS)».

То есть разработчики ГОСТ прогнали ТОТ ЖЕ алгоритм (Е.1) на воде и
опубликовали результат. Наш интегратор + CoolProp (тоже реализует IAPWS-95)
должны попасть в эти графики. Это сквозная проверка всей цепочки:
сетка -> плотность на изоэнтропе в двухфазной области -> трапеции Е.1.4 ->
поиск первого максимума -> Кп кр. Совпадение по диапазону осей и по
порядку кривых доказывает, что интегратор считает то же, что и стандарт.

Запуск:
    d:\\Studies\\Diplom\\env\\Scripts\\python.exe validate_gost.py
"""
from __future__ import annotations

import math
import sys

import numpy as np

if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')

from pk_gost import analytic as an, coeffs as cf, integrate as integ, thermo as th

LINE = '=' * 78
THIN = '-' * 78
_fails = []


def check(name, value, lo, hi, unit=''):
    """Проверка попадания в интервал, считанный с графика ГОСТ."""
    ok = lo <= value <= hi
    if not ok:
        _fails.append(name)
    print(f'  [{"OK" if ok else "!!"}] {name:<44} {value:9.4f}{unit}  '
          f'ожидалось {lo:.4f}...{hi:.4f}')
    return ok


def head(t):
    print()
    print(LINE)
    print(t)
    print(LINE)


