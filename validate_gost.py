    print('  При omega -> большие beta_кр -> 1,0; Кп кр -> 0 (см. Е.3).')
    print()
    print(f'  {"omega":>8} {"beta_кр числ.":>14} {"(Е.2.12) аппр.":>15} '
          f'{"Кп кр":>9}')
    print(' ' + THIN)
    for om in (0.1, 0.5, 1.0, 2.0, 5.0, 10.0, 25.0, 100.0):
        b = an.beta_cr_omega(om)
        a = an.beta_cr_omega_approx(om)
        print(f'  {om:8.2f} {b:14.5f} {a:15.5f} {an.Kn_cr_omega(om):9.4f}')
    print(' ' + THIN)
    check('Е.3: beta_кр при omega = 1 (= 1/sqrt(e))', an.beta_cr_omega(1.0), 0.604, 0.609)
    check('Е.3: Кп кр  при omega = 1', an.Kn_cr_omega(1.0), 0.604, 0.609)
    check('Е.3: beta_кр при omega = 10 (с графика ~0,85)',
          an.beta_cr_omega(10.0), 0.82, 0.88)
    check('Е.3: beta_кр при omega = 100 (стремится к 1,0)',
          an.beta_cr_omega(100.0), 0.94, 1.00)
    check('Е.3: Кп кр при omega = 100 (стремится к 0)',
          an.Kn_cr_omega(100.0), 0.05, 0.12)
    # согласие численного решения с аппроксимацией стандарта
    worst = max(abs(an.beta_cr_omega(o) - an.beta_cr_omega_approx(o)) / an.beta_cr_omega(o)
                for o in (0.5, 1, 2, 5, 10, 25))
    check('Согласие численного beta_кр с аппроксимацией (Е.2.12), макс. отн.',
          worst, 0.0, 0.005)


