# 5. Рисунки Е.9 / Е.10 — ВЛАЖНЫЙ ВОДЯНОЙ ПАР  (главный эталон)
# =========================================================================
def validate_fig_E9_E10():
    head('5. РИСУНКИ Е.9 / Е.10 — Кп кр для ВЛАЖНОГО ВОДЯНОГО ПАРА')
    print('  Это НЕЗАВИСИМЫЙ ЧИСЛЕННЫЙ ЭТАЛОН: по п. Е.4.1 графики Е.9-Е.13')
    print('  «рассчитаны методом прямого интегрирования по... уравнениям IAPWS».')
    print('  Разработчики ГОСТ прогнали тот же алгоритм (Е.1) на воде.')
    print('  Наш интегратор + CoolProp (IAPWS-95) должны попасть в те же графики.')
    print()
    water = th.Fluid('Water')
    print(f'  CoolProp: Ткр = {water.T_crit:.3f} К, Ркр = {water.P_crit/1e6:.4f} МПа')
    print(f'  ГОСТ Е.4.2: Ткр = 647,096 К, Rуд = 461,526 Дж/(кг·К)')
    check('Ткр воды против п. Е.4.2 (647,096 К)', water.T_crit, 647.05, 647.15, ' К')
    check('Rуд воды против п. Е.4.2 (461,526)', water.R_specific, 461.3, 461.8,
          ' Дж/(кг·К)')

    xs = (1.0, 0.9, 0.8, 0.7, 0.6, 0.5)

    def Kn_cr(P1, x):
        s1 = water.s_liq_sat(P1) + x * (water.s_gas_sat(P1) - water.s_liq_sat(P1))
        rho1 = water.rho_Ps(P1, s1)
        sol = integ.solve(water, P1, s1, min(0.02e6, 0.1 * P1), n_points=12000)
        return sol.G_ideal / math.sqrt(P1 * rho1)

    print()
    print('  --- рис. Е.9: Р1 = 0,1...10 МПа, ось Кп кр = 0,58...0,64 ---')
    print(f'  {"Р1, МПа":>8}' + ''.join(f'{f"  x={x:.1f}":>8}' for x in xs))
    print(' ' + THIN)
    vals_E9 = []
    for P1 in (0.1e6, 0.2e6, 0.5e6, 1.0e6, 2.0e6, 5.0e6, 10.0e6):
        row = [Kn_cr(P1, x) for x in xs]
        vals_E9 += row
        print(f'  {P1/1e6:8.2f}' + ''.join(f'{v:8.4f}' for v in row))
    print(' ' + THIN)
    check('Все значения рис. Е.9 в пределах оси графика (0,58...0,64)',
          min(vals_E9), 0.58, 0.64)
    check('  верхняя граница', max(vals_E9), 0.58, 0.64)
    ok = all(Kn_cr(P, 1.0) > Kn_cr(P, 0.5) for P in (0.1e6, 1.0e6, 10.0e6))
    print(f'  [{"OK" if ok else "!!"}] Порядок кривых: x = 1,0 выше x = 0,5 '
          f'(как на рис. Е.9)')
    if not ok:
        _fails.append('порядок кривых Е.9')

    print()
    print('  --- рис. Е.10: Р1 = 10...22 МПа, ось Кп кр = 0,52...0,62 ---')
    print(f'  {"Р1, МПа":>8}' + ''.join(f'{f"  x={x:.1f}":>8}' for x in xs))
    print(' ' + THIN)
    vals_E10 = []
    for P1 in (10.0e6, 12.0e6, 16.0e6, 20.0e6, 22.0e6):
        row = [Kn_cr(P1, x) for x in xs]
        vals_E10 += row
        print(f'  {P1/1e6:8.2f}' + ''.join(f'{v:8.4f}' for v in row))
    print(' ' + THIN)
    check('Все значения рис. Е.10 в пределах оси графика (0,52...0,62)',
          min(vals_E10), 0.52, 0.62)
    check('  верхняя граница', max(vals_E10), 0.52, 0.62)
    spread = max(Kn_cr(22e6, x) for x in xs) - min(Kn_cr(22e6, x) for x in xs)
    check('Кривые сходятся у критической точки (разброс при 22 МПа)',
          spread, 0.0, 0.03)


