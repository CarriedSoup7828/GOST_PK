def validate_table_I1():
    head('1. ТАБЛИЦА И.1 — критическое отношение давлений beta_кр')
    print('  Значения таблицы округлены до 3 знаков; сверяем с формулой (Е.2.4).')
    print()
    rows = [
        ('Азот / воздух / кислород / СО', 1.40, 0.528),
        ('Водород', 1.41, 0.527),
        ('Аргон', 1.67, 0.488),
        ('Аммиак', 1.32, 0.543),
        ('Метан / сероводород', 1.30, 0.547),
        ('Углекислый газ', 1.31, 0.545),
        ('Ацетилен', 1.23, 0.559),
        ('Бутан', 1.10, 0.586),
        ('Пропан / фреон 22', 1.14, 0.576),
        ('Хлористый метил', 1.20, 0.564),
        ('Этан', 1.22, 0.560),
        ('Этилен', 1.24, 0.557),
        ('Хлор', 1.34, 0.540),
    ]
    print(f'  {"среда":<32} {"k":>5} {"табл.И.1":>9} {"(Е.2.4)":>9} {"разн.":>8}')
    print(' ' + THIN)
    worst = 0.0
    for name, k, ref in rows:
        v = an.beta_cr_const_n(k)
        d = v - ref
        worst = max(worst, abs(d))
        flag = '' if abs(d) < 1.5e-3 else '  <<<'
        print(f'  {name:<32} {k:5.2f} {ref:9.3f} {v:9.5f} {d:+8.5f}{flag}')
    print(' ' + THIN)
    print(f'  Максимальное расхождение {worst:.5f} — в пределах округления таблицы.')
    if worst > 1.5e-3:
        _fails.append('табл. И.1')
    print()
    print('  ОТДЕЛЬНО — ГЕЛИЙ: таблица даёт k = 1,66 и beta_кр = 0,557.')
    print(f'    Формула (Е.2.4) при k = 1,66 даёт {an.beta_cr_const_n(1.66):.4f}.')
    print(f'    Значение 0,557 соответствует k = 1,24 — это строка ЭТИЛЕНА.')
    print('    => Ошибка переноса в самой таблице И.1. Для гелия считать по (Е.2.4).')


