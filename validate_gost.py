def validate_api520():
    head('9. API 520 / ISO 4126-1 — сверка с промышленной методикой')
    print('  API 520 Part 1 (в библиографии ГОСТ — источник [6]), критическое')
    print('  истечение газа/пара, единицы СИ:')
    print()
    print('      A [мм2] = W / (C * Kd * P1 * Kb * Kc) * sqrt(T*Z/M),')
    print('      C = 0,03948 * sqrt( k * (2/(k+1))^((k+1)/(k-1)) ),')
    print('      W в кг/ч, P1 в кПа абс., T в К, M в кг/кмоль.')
    print()
    print('  ГОСТ (Д.7): G = 3,60 * alpha*Kc*Kv*Kw * Кп кр * F * sqrt(P1[МПа]*rho1),')
    print('      где rho1 = P1*M/(Z*R*T)  (Е.3.13), R = 8314,3 Дж/(кмоль*К).')
    print()
    print('  Подстановка rho1 и перевод P1 в кПа даёт множитель')
    print('      3,60 / sqrt(8314,3) / 1000 = %.6f,' % (3.60 / math.sqrt(8314.3) / 1000 * 1000))
    print('  то есть C(API) = 0,03948 * Кп кр(ГОСТ), а Kd(API) = alpha(ГОСТ).')
    print('  ФОРМУЛЫ АЛГЕБРАИЧЕСКИ ТОЖДЕСТВЕННЫ. Проверка численно:')
    print()
    coef = 3.60 / math.sqrt(8314.3)
    print(f'  Точное значение множителя ГОСТ: 3,60/sqrt(8314,3) = {coef:.7f}')
    print(f'  Константа API округлена до 4 значащих цифр:        0,0394800')
    print(f'  => остаточное расхождение {abs(coef-0.03948)/0.03948:.1e} — это')
    print(f'     округление константы в API, а не разница методик.')
    check('Множитель 3,60/sqrt(R) против константы API 0,03948',
          coef, 0.03944, 0.03952)

    print()
    print(f'  {"k":>5} {"Кп кр (Е.2.6)":>14} {"C по API":>10} {"C/0,03948":>11} '
          f'{"разница":>9}')
    print(' ' + THIN)
    worst = 0.0
    for k in (1.0, 1.1, 1.2, 1.3, 1.4, 1.5, 1.67, 2.0):
        Kn = an.Kn_cr_const_n(k)
        C_api = 0.03948 * math.sqrt(k * (2.0 / (k + 1.0)) ** ((k + 1.0) / (k - 1.0))) \
            if abs(k - 1.0) > 1e-9 else 0.03948 / math.sqrt(math.e)
        d = abs(C_api / 0.03948 - Kn)
        worst = max(worst, d)
        print(f'  {k:5.2f} {Kn:14.5f} {C_api:10.5f} {C_api/0.03948:11.5f} {d:9.2e}')
    print(' ' + THIN)
    check('Кп кр (ГОСТ Е.2.6) == C/0,03948 (API 520), макс. расхождение',
          worst, 0.0, 1e-9)

    # сквозной численный пример: азот
    print()
    print('  Сквозной пример (азот, идеальный газ, k = 1,40):')
    k, M, T, Z = 1.40, 28.02, 300.0, 1.0
    P1_kPa, A_mm2, Kd = 676.3, 78.54, 0.75
    R = 8314.3
    rho1 = P1_kPa * 1000.0 * M / (Z * R * T)
    Kn = an.Kn_cr_const_n(k)
    G_gost = 3.60 * Kd * Kn * A_mm2 * math.sqrt(P1_kPa / 1000.0 * rho1)
    C_api = 0.03948 * math.sqrt(k * (2.0 / (k + 1.0)) ** ((k + 1.0) / (k - 1.0)))
    W_api = C_api * Kd * A_mm2 * P1_kPa * math.sqrt(M / (T * Z))
    print(f'    ГОСТ (Д.7):  G = {G_gost:9.3f} кг/ч')
    print(f'    API 520:     W = {W_api:9.3f} кг/ч')
    check('Расхождение ГОСТ (Д.7) и API 520 (только округление константы API)',
          abs(G_gost - W_api) / W_api, 0.0, 5e-5)


