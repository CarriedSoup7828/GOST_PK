import math

def calculate_safety_valve():
    # ==========================================
    # ИСХОДНЫЕ ДАННЫЕ (Замените на свои значения)
    # ==========================================
    
    # 1. Параметры процесса и теплоприток
    Q = 30000.0             # Теплоприток к резервуару, Вт (Дж/с)
    h_fg = 199000.0       # Скрытая теплота парообразования азота, Дж/кг (при ~77К)
    
    # 2. Давления
    P_n = 0.5             # Давление настройки ПК (избыточное), МПа
    overpressure = 0.10   # Превышение давления до полного открытия (обычно 10% или 0.10)
    P_atm = 0.1013        # Атмосферное давление, МПа
    P_back = 0.0          # Противодавление за клапаном (избыточное), МПа (0.0 если сброс в атмосферу)
    
    # 3. Температура и свойства азота (по ГОСТ 12.2.085-2017, Таблица И.1)
    T1_C = -190.0         # Температура азота перед клапаном, °C (температура насыщения при P_по)
    M = 28.02             # Молярная масса азота, кг/кмоль
    k = 1.40              # Показатель адиабаты (для азота)
    Z = 0.98              # Коэффициент сжимаемости (оценочно для криогенных температур и давлений)
    
    # 4. Характеристики клапана
    alpha = 0.85          # Коэффициент расхода для газа (альфа_1, берется из паспорта клапана)
    Kc = 1.0              # Коэф. влияния мембраны (1.0 - если мембраны нет)
    Kv = 1.0              # Коэф. вязкости (1.0 для газов)
    Kw = 1.0              # Коэф. противодавления (1.0 для неразгруженных клапанов при сбросе в атмосферу)
    
    R = 8314.3            # Универсальная газовая постоянная, Дж/(кмоль*К)
    
    # ==========================================
    # РАСЧЕТ ПО ГОСТ 12.2.085-2017
    # ==========================================

    # Шаг 1. Расчет требуемой пропускной способности (аварийный расход G_ав)
    # Формула: G_ав [кг/ч] = (Q [Дж/с] * 3600 [с/ч]) / h_fg [Дж/кг]
    G_av = (Q * 3600) / h_fg
    print(f"1. Требуемая пропускная способность (G_ав): {G_av:.2f} кг/ч")

    # Шаг 2. Определение расчетных давлений
    P_po = P_n * (1 + overpressure) # Давление полного открытия (изб.), МПа
    P1 = P_po + P_atm               # Абсолютное давление перед клапаном, МПа
    P2 = P_back + P_atm             # Абсолютное противодавление, МПа
    print(f"2. Абсолютное давление перед клапаном (P1): {P1:.3f} МПа")
    print(f"   Абсолютное давление за клапаном (P2): {P2:.3f} МПа")

    # Шаг 3. Расчет плотности азота перед клапаном
    T1_K = T1_C + 273.15
    # Уравнение состояния реального газа: rho = (P * M) / (Z * R * T)
    # Переводим P1 из МПа в Па (умножаем на 10^6)
    rho1 = (P1 * 1e6 * M) / (Z * R * T1_K)
    print(f"3. Плотность газообразного азота (rho1): {rho1:.2f} кг/м³")

    # Шаг 4. Определение режима истечения (Приложение Е, Таблица Е.1)
    # Для газа с постоянным показателем изоэнтропы n (принимаем n ≈ k)
    n = k 
    beta = P2 / P1
    beta_cr = (2 / (n + 1)) ** (n / (n - 1)) # Критическое отношение давлений
    
    if beta <= beta_cr:
        flow_type = "Критический (звуковой)"
        # Формула Е.2.6 для Kn_кр
        Kn = math.sqrt(n * (2 / (n + 1)) ** ((n + 1) / (n - 1)))
    else:
        flow_type = "Докритический (дозвуковой)"
        # Формула Е.2.3 для Kn
        Kn = math.sqrt((2 * n / (n - 1)) * (beta ** (2 / n) - beta ** ((n + 1) / n)))
        
    print(f"4. Режим истечения: {flow_type}")
    print(f"   Отношение давлений (beta): {beta:.3f} | Критическое (beta_cr): {beta_cr:.3f}")
    print(f"   Коэффициент Kn: {Kn:.4f}")

    # Шаг 5. Расчет минимальной площади седла клапана F (Приложение Д, Формула Д.7)
    # G = 3.60 * alpha * Kc * Kv * Kw * Kn * F * sqrt(P1 * rho1)
    # Где: G в кг/ч, F в мм², P1 в МПа, rho1 в кг/м³
    denominator = 3.60 * alpha * Kc * Kv * Kw * Kn * math.sqrt(P1 * rho1)
    F_req = G_av / denominator
    
    print("-" * 40)
    print(f"РЕЗУЛЬТАТ:")
    print(f"Требуемая минимальная площадь седла (F): {F_req:.2f} мм²")
    
    # Расчет соответствующего диаметра седла
    d0_req = math.sqrt((4 * F_req) / math.pi)
    print(f"Эквивалентный диаметр седла (d0): {d0_req:.2f} мм")
    

if __name__ == "__main__":
    calculate_safety_valve()