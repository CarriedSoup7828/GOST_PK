# -*- coding: utf-8 -*-
"""
Классификация режима течения (Д.10) и выбор метода расчёта (таблица Д.2).

Ключевой момент для азота, сбрасываемого из сосуда с жидкой фазой.
Азот — «регулярная» среда (п. 3.1.25, k = cp/cv = 1,40 > 1,1): при
изоэнтропном расширении вблизи линии насыщения он КОНДЕНСИРУЕТСЯ.
Поэтому режим Г-Г реализуется только при достаточном перегреве пара;
при малом перегреве изоэнтропа пересекает линию конденсации и
фактически имеет место режим Г-2Ф.

Различаются две классификации:

  * кинематическая — что делает изоэнтропа на всём отрезке [P2, P1]
    (именно так режимы определены в Д.10);
  * эффективная — что происходит до сечения запирания: если клапан
    запирается ВЫШЕ точки росы, за седлом фазового перехода ещё нет
    и расчёт по Г-Г корректен, хотя формально изоэнтропа ниже по потоку
    и уходит в двухфазную область.

Обе выводятся в протокол.
"""
from __future__ import annotations

from dataclasses import dataclass, field

from . import thermo as th

# Обозначения режимов по Д.10
GG = 'Г-Г'
G2F = 'Г-2Ф'
F2F2 = '2Ф-2Ф'
ZZ = 'Ж-Ж'
Z2F = 'Ж-2Ф'
SUPERCRIT = 'сверхкритическая среда'


@dataclass
class RegimeInfo:
    inlet_phase: str
    kinematic: str                  # режим по Д.10 на отрезке [P2, P1]
    effective: str = ''             # режим до сечения запирания
    P_dew: float | None = None      # давление начала конденсации (Е.3.3.2)
    P_bubble: float | None = None   # давление вскипания (Е.3.3.1)
    method: str = ''                # рекомендуемый метод по табл. Д.2
    method_ref: str = ''            # пункт стандарта
    notes: list = field(default_factory=list)
    superheat: float | None = None  # перегрев над Тнас(Р1), К
    T_sat: float | None = None


def classify(fluid, P1, T1, P2, s1=None):
    """
    Кинематическая классификация режима по Д.10.

    Возвращает RegimeInfo без поля effective — оно заполняется после
    расчёта массовой скорости функцией refine_with_solution().
    """
    if s1 is None:
        s1 = fluid.s_PT(P1, T1)

    info = RegimeInfo(inlet_phase='', kinematic='')

    # --- состояние на входе ---
    phase1 = fluid.phase_Ps(P1, s1)
    info.inlet_phase = phase1

    if phase1 == th.PHASE_SUPERCRIT:
        info.kinematic = SUPERCRIT
        info.method = 'постоянный показатель изоэнтропы либо омега-метод'
        info.method_ref = 'табл. Д.2 (суперкритическая область), Е.2.2'
        info.notes.append(
            'Р1 выше критического давления среды: применимость упрощённых '
            'уравнений состояния см. рис. Д.2; при сомнениях — метод прямого '
            'интегрирования (Е.1.1).')
        return info

    # --- перегрев над линией насыщения ---
    try:
        T_sat = fluid.T_sat(P1)
        info.T_sat = T_sat
        info.superheat = T1 - T_sat
    except th.ThermoError:
        pass

    # --- пересечения изоэнтропы с границами двухфазной области ---
    info.P_dew = fluid.dew_pressure(P1, P2, s1)
    info.P_bubble = fluid.bubble_pressure(P1, P2, s1)

    if phase1 == th.PHASE_GAS:
        if info.P_dew is None:
            info.kinematic = GG
            info.method = 'постоянный показатель изоэнтропы'
            info.method_ref = 'табл. Д.2, режим Г-Г; п. Е.2.2'
            info.notes.append(
                'Изоэнтропа не пересекает линию конденсации: среда на всём '
                'протяжении течения газообразна (Д.10, п. 3).')
        else:
            info.kinematic = G2F
            info.method = ('постоянный показатель изоэнтропы с разными '
                           'значениями n для газа и двухфазной области')
            info.method_ref = 'табл. Д.2, режим Г-2Ф; п. Е.2.3.2'
            info.notes.append(
                f'Изоэнтропа пересекает линию конденсации при '
                f'{info.P_dew/1e5:.3f} бар абс.: возникает конденсация газа '
                f'(Д.10, п. 4). Азот — «регулярная» среда (3.1.25), для неё '
                f'это штатное поведение вблизи насыщения.')
    elif phase1 == th.PHASE_TWOPHASE:
        info.kinematic = F2F2
        info.method = 'омега-метод'
        info.method_ref = 'табл. Д.2, режим 2Ф-2Ф; п. Е.2.2 (омега), Е.3.1.3'
        info.notes.append(
            'Среда на входе двухфазная. Предельный вариант режима 2Ф-2Ф — '
            'сброс газа на линии конденсации, т.е. насыщенного пара (Д.10, п. 5).')
        info.notes.append(
            'ВНИМАНИЕ. П. 5.8 требует устанавливать ПК в зоне газовой (паровой) '
            'фазы. Двухфазный состав на входе означает либо иное место установки, '
            'либо феномен подъёма уровня при вскипании (Г.3.1): «если смесь '
            'достигает входного патрубка клапана, то фазовый состав среды '
            'меняется с однофазного газового на двухфазный». Проверьте '
            'критический порог наполнения по Г.3.3.')
    else:  # жидкость
        if info.P_bubble is None:
            info.kinematic = ZZ
            info.method = 'несжимаемая жидкость'
            info.method_ref = 'табл. Д.2, режим Ж-Ж; п. Е.2.1'
        else:
            info.kinematic = Z2F
            info.method = 'несжимаемая жидкость + омега-метод'
            info.method_ref = 'табл. Д.2, режим Ж-2Ф; п. Е.2.3.1'
        info.notes.append(
            'ВНИМАНИЕ. На входе в клапан ЖИДКОСТЬ, а не пар. Для сосуда с '
            'жидким азотом это противоречит п. 5.8 («клапаны следует '
            'устанавливать в зоне газовой (паровой) фазы»). Проверьте Т1 и '
            'место установки ПК; если жидкость на входе действительно '
            'возможна, требуется анализ по Г.3 (подъём уровня) и учёт '
            'неравновесного вскипания по Е.5.')

    return info


def refine_with_solution(info: RegimeInfo, sol, rel_tol=2e-3):
    """
    Эффективная классификация с учётом положения сечения запирания.

    Если Ркр > Pросы, поток запирается ещё в газовой области — для расчёта
    пропускной способности это эквивалентно Г-Г. Если Ркр совпал с Pросы
    (в пределах rel_tol), это особый случай Е.1.5: показатель изоэнтропы
    и скорость звука терпят скачок на границе фазовой диаграммы.
    """
    info.effective = info.kinematic

    if info.kinematic != G2F or info.P_dew is None:
        return info

    if sol.regime != 'критический':
        info.notes.append(
            'Режим докритический: течение доходит до Р2 в двухфазной области.')
        return info

    rel = abs(sol.P0 - info.P_dew) / sol.P1

    if rel <= rel_tol:
        info.effective = f'{G2F} (граничный случай: Ркр = Ркoнд)'
        info.notes.append(
            f'ВНИМАНИЕ. Критическое давление {sol.P0/1e5:.4f} бар совпало с '
            f'давлением начала конденсации {info.P_dew/1e5:.4f} бар — особый '
            f'случай п. Е.1.5: «показатель изоэнтропы и скорость звука могут '
            f'испытывать скачок на границе фазовой диаграммы», и вместо '
            f'равенства выполняется лишь неравенство '
            f'sqrt(n-*Pкр*rho_кр) <= G*ideal <= sqrt(n+*Pкр*rho_кр). '
            f'Расчёт корректен, но результат чувствителен к перегреву: '
            f'проверьте таблицу чувствительности.')
    elif sol.P0 > info.P_dew:
        info.effective = f'{GG} (запирание выше Ркoнд)'
        info.notes.append(
            f'Клапан запирается при {sol.P0/1e5:.3f} бар — ВЫШЕ давления начала '
            f'конденсации {info.P_dew/1e5:.3f} бар. До сечения запирания среда '
            f'газообразна, поэтому для расчёта пропускной способности режим '
            f'эквивалентен Г-Г; конденсация происходит уже за седлом и на '
            f'величину G не влияет.')
    else:
        info.effective = G2F
        info.notes.append(
            f'Клапан запирается при {sol.P0/1e5:.3f} бар — НИЖЕ давления начала '
            f'конденсации {info.P_dew/1e5:.3f} бар: сечение запирания лежит в '
            f'двухфазной области, режим Г-2Ф реализуется полностью.')
    return info


def min_superheat_for_GG(fluid, P1, P2, hi=80.0, tol=1e-3):
    """
    Минимальный перегрев над Тнас(Р1), при котором клапан запирается ещё в
    газовой области (Pросы < Ркр), т.е. режим фактически Г-Г.

    Полезен как справочная величина: показывает, насколько текущая точка
    далека от границы применимости расчёта по Г-Г.
    """
    from . import integrate as integ

    T_sat = fluid.T_sat(P1)

    def is_GG(dT):
        s1 = fluid.s_PT(P1, T_sat + dT)
        P_dew = fluid.dew_pressure(P1, P2, s1)
        if P_dew is None:
            return True
        sol = integ.solve(fluid, P1, s1, P2, n_points=4000)
        return sol.regime == integ.REGIME_CRITICAL and P_dew < sol.P0

    if not is_GG(hi):
        return None
    lo = tol
    if is_GG(lo):
        return 0.0
    for _ in range(60):
        mid = 0.5 * (lo + hi)
        if is_GG(mid):
            hi = mid
        else:
            lo = mid
        if hi - lo < tol:
            break
    return hi
