# -*- coding: utf-8 -*-
"""
Поправочные коэффициенты формулы (Д.1):

    G = alpha * Kc * Kv * Kw * G*ideal * F

  Д.5   alpha — коэффициент расхода (alpha1 при критическом режиме,
        alpha2 при докритическом)
  Д.6   Kc    — мембранно-предохранительные устройства
  Д.7   Kv    — высоковязкие среды (Д.11-Д.14), итерации Д.9
  Д.8   Kw    — неполное открытие разгруженных ПК из-за противодавления
        (таблица Д.1)

ИСПРАВЛЕНО ПРОТИВ ИСХОДНОГО СКРИПТА
-----------------------------------
Формула (Д.12) записывалась как `0.9935 + 2.8780/Re + 342.75/Re**1.5`,
то есть без возведения всей скобки в степень (-1) и с Re вместо Re^0,5.
При Re = 1000 это давало Kv = 1,007 > 1, что физически невозможно.
Формула (Д.13) для Re < 1000 была записана как `0.975/Re + 0.980`.
Правильность прочтения подтверждается сшивкой на границе Re = 1000:
(Д.12) даёт 0,9130, (Д.13) даёт 0,9092 — расхождение 0,4 %.
"""
from __future__ import annotations

import numpy as np

RE_TURBULENT = 1.0e5      # Д.7: при Re >= 100 000 допускается принимать Kv = 1,0
RE_LOW = 1.0e3            # граница между (Д.12) и (Д.13)


# =========================================================================
#  Д.5  Коэффициент расхода alpha
# =========================================================================
def alpha_for_regime(regime, alpha1, alpha2, seat_pressure_known=False):
    """
    Выбор коэффициента расхода по Д.5.

    «alpha1 (для критического течения газа) — при критическом режиме течения
     через клапан; alpha2 (для течения жидкости и газа) — при докритическом
     режиме истечения через клапан.»

    seat_pressure_known — изготовитель указал, как рассчитать давление в седле P0
        по Р1 и Р2 (Д.4.3); тогда и при докритическом режиме применяют alpha1.
    """
    if regime == 'критический' or seat_pressure_known:
        return alpha1, ('alpha1 — критический режим (Д.5)' if regime == 'критический'
                        else 'alpha1 — использовано давление в седле P0 (Д.4.3, Д.5)')
    return alpha2, 'alpha2 — докритический режим, за выходное принято P2 (Д.4.3, Д.5)'


def P0_from_alphas(P1, P2, alpha1, alpha2):
    """
    (Д.4.3) Оценка абсолютного давления в седле:
        P0 = (alpha2^2/alpha1^2)*P2 + (1 - alpha2^2/alpha1^2)*P1
    При использовании этой оценки в расчёте применяют alpha1.
    """
    r = (alpha2 / alpha1) ** 2
    return r * P2 + (1.0 - r) * P1


# =========================================================================
#  Д.6  Коэффициент Kc
# =========================================================================
def Kc(membrane_device=False):
    """
    (Д.6) Kc = 0,9 при установке мембранно-предохранительных устройств
    до или после клапана; Kc = 1,0 при их отсутствии.
    """
    return 0.9 if membrane_device else 1.0


# =========================================================================
#  Д.7  Коэффициент Kv (вязкость)
# =========================================================================
def Kv_from_Re(Re):
    """
    Поправка на вязкость по числу Рейнольдса — формулы (Д.12), (Д.13), (Д.7).

    (Д.12) 1000 <= Re <= 100 000:
        Kv = (0,9935 + 2,8780/Re^0,5 + 342,7500/Re^1,5)^(-1)
    (Д.13) Re < 1000:
        Kv = 0,975 * sqrt( 1 / (170/Re + 0,980) )
    (Д.7)  Re >= 100 000:  Kv = 1,0
    """
    Re = float(Re)
    if Re <= 0.0:
        raise ValueError('Число Рейнольдса должно быть положительным')
    if Re >= RE_TURBULENT:
        return 1.0
    if Re >= RE_LOW:
        return float((0.9935 + 2.8780 / np.sqrt(Re) + 342.7500 / Re ** 1.5) ** -1)
    return float(0.975 * np.sqrt(1.0 / (170.0 / Re + 0.980)))


def Kv_full(Re, d0, DN1):
    """
    (Д.11) Полная формула, когда отношение d0/DN1 уже известно:

        Kv = 0,975 * sqrt( (d0/DN1)^0,1 / (950*(1 - d0/DN1)^1,4/Re + 0,900) )
    """
    r = d0 / DN1
    if not 0.0 < r < 1.0:
        raise ValueError(f'Отношение d0/DN1 должно быть в (0,1), получено {r:.4f}')
    if Re >= RE_TURBULENT:
        return 1.0
    return float(0.975 * np.sqrt(r ** 0.1 / (950.0 * (1.0 - r) ** 1.4 / Re + 0.900)))


def reynolds_from_G(G, d0, mu):
    """(Д.14) Re = 4*G/(pi*mu*d0), СИ: G в кг/с, d0 в м, mu в Па*с."""
    return float(4.0 * G / (np.pi * mu * d0))


def reynolds_from_G_F(G, F, mu):
    """(Д.14) Re = (G/mu)*sqrt(4/(pi*F)) — форма через площадь седла."""
    return float(G / mu * np.sqrt(4.0 / (np.pi * F)))


def mu_two_phase(x, mu_g, mu_l, rho_g, rho_l):
    """
    (Д.15) Эффективная динамическая вязкость двухфазной газожидкостной смеси:
        mu = eps*mu_g + (1 - eps)*(1 + 2,5*eps)*mu_l,
        eps = [1 + (1-x)/x * rho_g/rho_l]^(-1)
    """
    if x <= 0.0:
        return mu_l
    if x >= 1.0:
        return mu_g
    eps = 1.0 / (1.0 + (1.0 - x) / x * rho_g / rho_l)
    return float(eps * mu_g + (1.0 - eps) * (1.0 + 2.5 * eps) * mu_l)


def iterate_Kv(G_of_Kv, Re_of_G, Kv_func=Kv_from_Re, tol_rel=0.005, max_iter=50):
    """
    Итерационное определение Kv — алгоритм Д.9.1 / Д.9.3.

    «принять Kv = 1,0 и определить Re0...; если Re0 >= 100000, то Kv = 1,0;
     если Re0 < 100000, то Kv определить из уравнения Re = Kv(Re)*Re0,
     например методом последовательных итераций.»
    Итерации ведут, «пока изменение dKv = Kv(i+1) - Kv(i) не будет меньше,
    чем 0,5 % от значения Kv(i), полученного на предыдущем шаге» (Д.9).

    G_of_Kv  — функция Kv -> расход (или массовая скорость)
    Re_of_G  — функция расход -> число Рейнольдса
    Возвращает (Kv, Re, число итераций).
    """
    Kv = 1.0
    Re = Re_of_G(G_of_Kv(1.0))
    if Re >= RE_TURBULENT:
        return 1.0, Re, 0
    for it in range(1, max_iter + 1):
        Kv_new = Kv_func(Re)
        converged = abs(Kv_new - Kv) < tol_rel * Kv
        Kv = Kv_new
        Re = Re_of_G(G_of_Kv(Kv))
        if converged:
            return Kv, Re, it
    return Kv, Re, max_iter


# =========================================================================
#  Д.8 / таблица Д.1  Коэффициент Kw
# =========================================================================
def _Kw_liquid(r):
    """(Д.21) Жидкость, все Рпо/Рн."""
    if r <= 0.150:
        return 1.0
    if r <= 0.250:
        return 0.8750 + 1.8333 * r - 6.6667 * r ** 2
    return 1.1490 - 0.9880 * r


def _Kw_gas_110(r):
    """(Д.22) Газ, Рпо/Рн = 1,10."""
    if r <= 0.300:
        return 1.0
    return 1.1027 + 0.4007 * r - 2.4577 * r ** 2


def _Kw_gas_115(r):
    """(Д.23) Газ, Рпо/Рн = 1,15."""
    if r <= 0.377:
        return 1.0
    return 1.2857 - 0.7603 * r


def _Kw_gas_120(r):
    """(Д.24) Газ, Рпо/Рн более 1,20: Kw = 1,0 вплоть до Рп/Рно = 0,500."""
    return 1.0


def Kw(ratio_back_no, ratio_po_n, medium='газ', balanced=True, regime='критический'):
    """
    Поправочный коэффициент на неполное открытие разгруженного ПК
    из-за противодавления — таблица Д.1.

    ratio_back_no — Рп/Рно
    ratio_po_n    — Рпо/Рн (ключ входа в таблицу)
    medium        — 'газ' | 'жидкость' | 'двухфазная'
    balanced      — разгруженный клапан; для неразгруженных Kw = 1,0
                    (примечание 2 к таблице Д.1)
    regime        — для двухфазных сред: при критическом режиме Kw по
                    (Д.22)-(Д.26), при докритическом — по (Д.21)
                    (примечание 1 к таблице Д.1)

    Возвращает (Kw, пояснение).
    """
    if not balanced:
        return 1.0, 'Kw = 1,0 — клапан неразгруженный (табл. Д.1, прим. 2)'

    r = float(ratio_back_no)

    if medium == 'двухфазная':
        medium = 'жидкость' if regime == 'докритический' else 'газ'
        note_2f = ' (двухфазная среда, табл. Д.1 прим. 1)'
    else:
        note_2f = ''

    if medium == 'жидкость':
        return _Kw_liquid(r), f'(Д.21) жидкость, Рп/Рно = {r:.3f}{note_2f}'

    # --- газ: вход по Рпо/Рн ---
    q = float(ratio_po_n)
    if q <= 1.10:
        return _Kw_gas_110(r), f'(Д.22) газ, Рпо/Рн = {q:.3f}, Рп/Рно = {r:.3f}{note_2f}'
    if abs(q - 1.15) < 1e-9:
        return _Kw_gas_115(r), f'(Д.23) газ, Рпо/Рн = 1,15, Рп/Рно = {r:.3f}{note_2f}'
    if q < 1.15:
        # (Д.25) линейная интерполяция по Рпо/Рн между (Д.22) и (Д.23)
        w = (q - 1.10) / (1.15 - 1.10)
        val = (1.0 - w) * _Kw_gas_110(r) + w * _Kw_gas_115(r)
        return val, (f'(Д.25) газ, интерполяция по Рпо/Рн = {q:.3f} '
                     f'между (Д.22) и (Д.23), Рп/Рно = {r:.3f}{note_2f}')
    if q <= 1.20:
        # (Д.26) линейная интерполяция между (Д.23) и (Д.24)
        w = (q - 1.15) / (1.20 - 1.15)
        val = (1.0 - w) * _Kw_gas_115(r) + w * _Kw_gas_120(r)
        return val, (f'(Д.26) газ, интерполяция по Рпо/Рн = {q:.3f} '
                     f'между (Д.23) и (Д.24), Рп/Рно = {r:.3f}{note_2f}')
    return _Kw_gas_120(r), f'(Д.24) газ, Рпо/Рн = {q:.3f} > 1,20, Рп/Рно = {r:.3f}{note_2f}'
