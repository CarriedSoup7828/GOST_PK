# -*- coding: utf-8 -*-
"""
Аварийный расход Gав — приложение Г.

Рассматриваемый сценарий: нарушение теплового баланса (Г.1.2) — внешний
теплоприток к сосуду с жидким азотом. По Г.2 для «простых» случаев
поверхностного вскипания однокомпонентной жидкости «расчёт сводят к оценке
притока тепла в единицу времени и порождаемого им увеличения объёма
продукта в аппарате... из-за вскипания (расчёт с использованием скрытой
теплоты испарения)»:

    Gав = Q / h_gl(P1)

где h_gl = h_g - h_l — скрытая теплота парообразования при давлении сброса.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass
class ReliefLoad:
    Q: float                 # Вт, подводимая тепловая мощность
    h_fg: float              # Дж/кг, скрытая теплота парообразования при P1
    G_av: float              # кг/с, аварийный расход по Г.2
    G_av_enthalpy: float     # кг/с, вариант по полной разности энтальпий
    dh_total: float          # Дж/кг, h(P1,T1) - h_l(P1)
    note: str = ''

    @property
    def G_av_kgh(self):
        return self.G_av * 3600.0


def relief_load(fluid, Q, P1, T1):
    """
    Аварийный расход от теплопритока.

    Основной вариант (по Г.2) — через скрытую теплоту парообразования:
        Gав = Q / h_gl(P1)
    Он консервативен: весь подведённый теплопоток относится на выпаривание,
    а перегрев пара считается обеспеченным отдельным теплопритоком к сухой
    стенке паровой зоны.

    Справочный вариант — через полную разность энтальпий от кипящей жидкости
    до фактического состояния на входе в клапан:
        Gав' = Q / (h(P1,T1) - h_l(P1))
    Он даёт МЕНЬШИЙ расход (знаменатель больше), т.е. НЕ в запас, и приводится
    только для оценки, какая доля тепла идёт на перегрев.
    """
    if P1 >= fluid.P_crit:
        from .thermo import ThermoError
        raise ThermoError(
            f'Р1 = {P1/1e5:.3f} бар >= Ркр = {fluid.P_crit/1e5:.3f} бар для '
            f'{fluid.name}: скрытой теплоты парообразования не существует, '
            f'расчёт Gав по Г.2 неприменим. Для сверхкритической среды '
            f'аварийный расход определяют из теплового расширения в '
            f'ограниченном объёме (Г.1.2, Г.2), а не из вскипания.')

    h_fg = fluid.h_fg(P1)
    h_l = fluid.h_liq_sat(P1)
    h1 = fluid.h_PT(P1, T1)
    dh_total = h1 - h_l

    G_av = Q / h_fg
    G_av_h = Q / dh_total if dh_total > 0 else float('nan')

    share = (dh_total - h_fg) / dh_total * 100.0 if dh_total > 0 else 0.0
    note = (f'на перегрев пара приходится {share:.1f} % полной разности энтальпий; '
            f'по Г.2 принят консервативный вариант через h_gl')

    return ReliefLoad(Q=Q, h_fg=h_fg, G_av=G_av, G_av_enthalpy=G_av_h,
                      dh_total=dh_total, note=note)
