# -*- coding: utf-8 -*-
"""
Исходные данные расчёта.

Поля, значения которых пока не подтверждены документацией, перечисляются
в множестве `stubs` и помечаются в протоколе как ЗАГЛУШКА, чтобы результат
нельзя было принять за окончательный.
"""
from __future__ import annotations

from dataclasses import dataclass, field

P_ATM_DEFAULT = 101320.0     # Па, п. 3.4


@dataclass
class ValveCase: 
    """Один расчётный случай: среда, сценарий, давления, клапан."""

    # ---------------- среда и сценарий ----------------
    fluid: str = 'Nitrogen'
    T1: float = 107.5                 # К, температура среды перед клапаном (п. 3.4)
    Q_heat: float = 20_000.0          # Вт, аварийный теплоприток (прил. Г.1.2)

    # ---------------- давления (избыточные, Па) ----------------
    P_n_g: float = 5.0e5              # Рн   — давление настройки (3.1.1)
    P_no_g: float | None = None       # Рно  — давление начала открытия (3.1.4); None -> = Рн
    P_po_g: float | None = None       # Рпо  — задать явно, иначе по 5.4
    P_work_g: float = 3.0e5           # Рр   — рабочее давление (3.1.6)
    P_design_g: float = 6.0e5         # Р    — расчётное давление (3.1.8)
    P_av_max_g: float = 6.6e5         # Рав max — макс. давление аварийного сброса (3.1.2)
    P_allowed_g: float | None = None  # Рраз — разрешённое давление (3.1.7)
    P_back_static_g: float = 0.0      # Рп ст — статическое противодавление (3.1.24)
    P_back_dyn_g: float = 0.0         # Рп дин — динамическое противодавление (3.1.23)
    dP_in: float = 0.0                # dPвх — потери давления на входе (3.1.13)
    P_atm: float = P_ATM_DEFAULT

    # ---------------- клапан ----------------
    alpha1: float = 0.75              # коэффициент расхода для газа (3.1.11)
    alpha2: float = 0.65              # коэффициент расхода для жидкости (3.1.11)
    F_mm2: float | None = None        # площадь седла, мм2 (для поверочного расчёта)
    DN1_mm: float | None = None       # номинальный диаметр входного патрубка
    N: int = 1                        # число параллельно работающих клапанов (п. 3.4)
    balanced: bool = False            # разгруженный ПК (3.1.19)
    membrane_device: bool = False     # мембранно-предохранительное устройство (Д.6)
    seat_pressure_known: bool = False # изготовитель дал расчёт P0 в седле (Д.4.3)

    # ---------------- служебное ----------------
    title: str = 'Азот, аварийный теплоприток'
    stubs: set = field(default_factory=set)
    catalog_d0_mm: tuple = (6, 8, 10, 12, 16, 20, 25, 32, 40, 50, 65, 80, 100, 125, 150)

    def is_stub(self, name):
        return name in self.stubs

    def mark(self, name):
        """Пометка «ЗАГЛУШКА» для протокола."""
        return '   <-- ЗАГЛУШКА, уточнить' if name in self.stubs else ''


def default_case():
    """
    Пример исходных данных для сосуда с жидким азотом под внешним теплопритоком.

    ВСЕ ЧИСЛА, ПОМЕЧЕННЫЕ КАК ЗАГЛУШКИ, — ориентировочные и подлежат замене
    данными ЭД клапана (5.11) и паспорта сосуда.
    """
    case = ValveCase(
        fluid='Nitrogen',
        T1=130,                     # перегретый пар: Тнас(Р1) ~ 98 К + 20 К
        Q_heat=3_000.0,
        P_n_g=5.0e5,
        P_work_g=3.0e5,
        P_design_g=6.0e5,
        P_av_max_g=6.6e5,
        P_back_static_g=0.0,          # сброс в атмосферу
        P_back_dyn_g=0.0,
        dP_in=0.0,
        alpha1=0.75,
        alpha2=0.65,
        F_mm2=None,                   # проектная задача: F определяется расчётом
        N=1,
        balanced=False,
        title='Азот, сброс из сосуда с жидкой фазой при внешнем теплопритоке',
    )
    case.stubs = {
        'T1', 'Q_heat', 'P_n_g', 'P_work_g', 'P_design_g', 'P_av_max_g',
        'alpha1', 'alpha2', 'balanced', 'N',
    }
    return case
