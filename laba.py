import numpy as np
import matplotlib.pyplot as plt

# ==========================================
# 1. Исходные данные (из вашего Excel, "чистый" линейный участок)
# ==========================================
U = np.array([810, 870 ,900, 920, 960, 1000, 1080, 1160, 1210, 1295, 1350, 1380, 1420]) # Напряжение, В
E_gen_exp = np.array([0.9, 6.5, 7.5, 15,11.5, 18.5, 25.0, 31.0, 37.0, 43.0, 49.0, 57.0, 66.0]) # Энергия генерации, мДж

# ==========================================
# 2. Константы установки и параметры из расчетов
# ==========================================
C = 560e-6       # Емкость батареи, Ф (560 мкФ)
tau_imp = 350e-6 # Длительность импульса, с (350 мкс)

# Критическая мощность (из расчетов в отчете)
P_k_full = 304.0 # Вт (для полного объема стержня, дает завышение)
P_k_eff = 45.0   # Вт (для эффективного объема с диафрагмой 3 мм, дает хорошее совпадение)

# ==========================================
# 3. Расчет энергии накачки и линейная аппроксимация
# ==========================================
# E_pump = C * U^2 / 2  (в Джоулях)
E_pump = 0.5 * C * U**2

# Находим коэффициенты линии тренда y = k*x + b с помощью полиномиальной фитации 1-й степени
k, b = np.polyfit(E_pump, E_gen_exp, 1)

# Пороговая энергия - это точка пересечения с осью X (где y = 0)
# 0 = k * E_th + b  =>  E_th = -b / k
E_th = -b / k

print(f"--- Результаты аппроксимации ---")
print(f"Наклон (дифференциальный КПД) k = {k:.4f} мДж/Дж")
print(f"Свободный член b = {b:.2f} мДж")
print(f"Пороговая энергия E_th = {E_th:.2f} Дж")
print(f"Пороговое напряжение U_th = {np.sqrt(2 * E_th / C):.1f} В")
print("----------------------------------")

# ==========================================
# 4. Расчет теоретических значений
# ==========================================
# Создаем плавный массив точек для красивых линий от 0 до максимума E_pump
E_pump_line = np.linspace(0, np.max(E_pump) * 1.1, 100)

# Уравнение линии тренда эксперимента
E_gen_trend = k * E_pump_line + b

# Теоретическая формула: E_gen_theor = P_k * tau_imp * (E_pump / E_th - 1)
# Результат в Джоулях, умножаем на 1000, чтобы получить мДж (как в эксперименте)
E_gen_theor_full = P_k_full * tau_imp * (E_pump_line / E_th - 1) * 1000
E_gen_theor_eff = P_k_eff * tau_imp * (E_pump_line / E_th - 1) * 1000

# ==========================================
# 5. Построение графика
# ==========================================
plt.figure(figsize=(10, 6))

# 1. Экспериментальные точки
plt.scatter(E_pump, E_gen_exp, color='red', s=50, zorder=5, label='$E_{gen}$')

# 2. Линия тренда эксперимента
plt.plot(E_pump_line, E_gen_trend, color='red', linestyle='--', linewidth=2,
         label=f'Линия тренда') 
#$E_{{gen}} = {k:.4f} \\cdot E_{{pump}} {b:+.2f}$\n(Порог $E_{{th}} \\approx {E_th:.1f}$ Дж)')

# 3. Теоретическая линия (полный объем)
plt.plot(E_pump_line, E_gen_theor_full, color='blue', linestyle='-', linewidth=2,
         label='$E_{gen_{theor}}$')

# 4. Теоретическая линия (эффективный объем с диафрагмой)
plt.plot(E_pump_line, E_gen_theor_eff, color='green', linestyle='-.', linewidth=2,
         label='$E_{gen_{theor diafragma}}$')

# Вертикальная линия, показывающая порог
plt.axvline(x=E_th, color='gray', linestyle=':', alpha=0.7)

# Оформление графика
# plt.title('Зависимость энергии генерации от энергии накачки', fontsize=14, fontweight='bold')
plt.xlabel('Энергия накачки $E_{pump}$, Дж', fontsize=12)
plt.ylabel('Энергия генерации $E_{gen}$, мДж', fontsize=12)
plt.grid(True, linestyle=':', alpha=0.7)
plt.legend(fontsize=11, loc='upper left')
plt.xlim(left=0)
plt.ylim(bottom=0)
# Отображение графика
plt.tight_layout()
plt.show()